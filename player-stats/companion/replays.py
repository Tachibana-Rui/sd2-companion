"""Bounded client replay-header discovery, not a replay simulation or parser.

Headers are candidate match metadata. They do not prove that a report belongs
to that session or that the client submission was generated by the server.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import re
import struct


MAX_HEADER = 2 * 1024 * 1024


class HeaderError(ValueError):
    pass


@dataclass(frozen=True)
class ReplayIdentity:
    session_id: str
    game_build: int
    map: str
    server_name: str
    participants: tuple[dict, ...]
    header_sha256: str
    source_path: str = ""
    observed_at: float = 0.0

    def public_metadata(self):
        return {"session_id": self.session_id, "game_build": self.game_build,
                "map": self.map, "server_name": self.server_name,
                "participants": list(self.participants), "client_header_sha256": self.header_sha256}


def _text(value, maximum=256):
    if not isinstance(value, str) or len(value) > maximum or any(ord(c) < 32 for c in value):
        raise HeaderError("invalid_header_text")
    return value


def _integer(value, maximum):
    if isinstance(value, bool) or not isinstance(value, (str, int)):
        raise HeaderError("invalid_header_integer")
    if isinstance(value, str) and not re.fullmatch(r"-?[0-9]{1,20}", value):
        raise HeaderError("invalid_header_integer")
    result = int(value)
    if not 0 <= result <= maximum:
        raise HeaderError("invalid_header_integer")
    return result


def _unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise HeaderError("duplicate_header_key")
        result[key] = value
    return result


def parse_header(data, *, source_path="", observed_at=0.0):
    if not isinstance(data, bytes) or len(data) < 32 or data[:8] != b"ESAV\0\0\0\x03":
        raise HeaderError("unsupported_replay_header")
    offset = 16
    for _ in range(16):
        if offset + 16 > len(data):
            raise HeaderError("incomplete_replay_header")
        tag, length, reserved = struct.unpack_from(">4sQI", data, offset)
        if reserved or length > MAX_HEADER or offset + 16 + length > len(data):
            raise HeaderError("incomplete_or_invalid_replay_header")
        end = offset + 16 + length
        if tag == b"rply":
            try:
                raw = json.loads(data[offset + 16:end].decode("utf-8"), object_pairs_hook=_unique,
                                 parse_constant=lambda _: (_ for _ in ()).throw(HeaderError("nonfinite_header_number")))
            except (UnicodeError, ValueError, RecursionError) as exc:
                raise HeaderError("invalid_replay_header_json") from exc
            break
        if tag != b"modd":
            raise HeaderError("unsupported_replay_header_block")
        offset = end
    else:
        raise HeaderError("missing_replay_identity")
    if not isinstance(raw, dict) or not isinstance(raw.get("game"), dict):
        raise HeaderError("missing_replay_identity")
    game = raw["game"]
    sid = _text(game.get("UniqueSessionId"), 128)
    if not sid:
        raise HeaderError("missing_session_id")
    build = _integer(game.get("Version"), 2**31 - 1)
    map_id = _text(game.get("Map"), 512)
    if not map_id or build <= 0:
        raise HeaderError("missing_map_or_build")
    name = _text(game.get("ServerName", ""))
    participants = []
    for key, player in raw.items():
        if not re.fullmatch(r"player_[0-9]{1,10}", key):
            continue
        if not isinstance(player, dict):
            raise HeaderError("invalid_replay_player")
        # Observers are not rows in the normal mission-report player list.
        if _integer(player.get("PlayerObserver", 0), 1) == 1:
            continue
        identity = str(_integer(player.get("PlayerUserId", 0), 2**64 - 1))
        participants.append({"id": identity, "name": _text(player.get("PlayerName", "")),
                             "alliance": _integer(player.get("PlayerAlliance", 0), 1)})
    if not 1 <= len(participants) <= 64:
        raise HeaderError("invalid_player_count")
    return ReplayIdentity(sid, build, map_id, name, tuple(participants),
                          hashlib.sha256(data[offset:end]).hexdigest(), str(source_path), observed_at)


class ReplayWatcher:
    """Observe new/changed headers only after an explicit baseline.

    It does not match old files using modification time. Distinct candidate
    sessions are returned for the state machine to disambiguate.
    """
    def __init__(self, directories, *, max_files=2000):
        self.directories = tuple(Path(x).resolve() for x in directories)
        self.max_files = max_files
        self._signatures = {}
        self._identities = {}
        self.initialized = False
        self.errors = 0

    def _files(self):
        files = []
        for directory in self.directories:
            try:
                for path in directory.iterdir():
                    if path.suffix.lower() in (".rpl3", ".rpl") and not path.is_symlink() and path.is_file():
                        value = path.stat()
                        files.append((value.st_mtime_ns, path, (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns)))
            except OSError:
                self.errors += 1
        return sorted(files, key=lambda x: (x[0], str(x[1])), reverse=True)[:self.max_files]

    def baseline(self):
        self._signatures = {str(p): signature for _, p, signature in self._files()}
        self.initialized = True

    def poll(self, now):
        if not self.initialized:
            self.baseline()
            return []
        found = []
        for _, path, signature in self._files():
            key = str(path)
            if self._signatures.get(key) == signature:
                continue
            try:
                with path.open("rb") as source:
                    data = source.read(MAX_HEADER + 32)
                identity = parse_header(data, source_path=key, observed_at=now)
                after = path.stat()
                if (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns) != signature:
                    continue
            except (OSError, HeaderError):
                self.errors += 1
                continue  # An incomplete header may become complete next poll.
            self._signatures[key] = signature
            if self._identities.get(key) != (identity.session_id, identity.header_sha256):
                self._identities[key] = (identity.session_id, identity.header_sha256)
                found.append(identity)
        return found

